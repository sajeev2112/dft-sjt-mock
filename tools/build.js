// Run after editing docs/questions.js:  node tools/build.js
// Validates every question and key, syncs the question-type list into the Worker,
// and stamps the service worker with a content hash so offline caches refresh.
const fs = require("fs"), path = require("path"), vm = require("vm"), crypto = require("crypto");
const root = path.join(__dirname, "..");
const read = f => fs.readFileSync(path.join(root, f), "utf8");

const ctx = {};
vm.runInNewContext(read("docs/questions.js") + ";this.Q=Q;this.THEMES=THEMES;this.DOMAINS=DOMAINS;", ctx);
const {Q, THEMES, DOMAINS} = ctx;
const errors = [];
Q.forEach((q, i) => {
  const id = `Q${i + 1}`;
  if (!["rank", "consider", "best3"].includes(q.t)) errors.push(`${id}: bad type`);
  if (!DOMAINS[q.d]) errors.push(`${id}: bad domain`);
  if (!THEMES[q.g]) errors.push(`${id}: bad theme`);
  const n = q.t === "best3" ? 8 : 5;
  if (!Array.isArray(q.o) || q.o.length !== n) errors.push(`${id}: needs ${n} options`);
  else q.o.forEach((o, j) => { if (!o[0] || !o[1]) errors.push(`${id}: option ${j + 1} missing text or justification`); });
  if (q.t === "best3") { if (!/^[A-H]{3}$/.test(q.k) || new Set(q.k).size !== 3) errors.push(`${id}: bad best-three key ${q.k}`); }
  else if (q.k.split("").sort().join("") !== "ABCDE") errors.push(`${id}: bad ranking key ${q.k}`);
  if (!q.s || !q.tk || !q.a) errors.push(`${id}: missing scenario, takeaway or archetype`);
});
// Action-type tag for every option (tools/tags.json, written once by a tagging pass), used by the Study plan to spot habits such as
// "ranks passing it to a senior too high". Each question's signature must still match its option texts, so editing an option
// forces a re-tag instead of silently misaligning the letters.
const TAG_LABELS = {a:"talking to the person directly", b:"passing it to a senior or manager", c:"reporting formally or to an outside body",
  d:"supporting or reassuring someone", e:"gathering facts first", f:"acting on the clinical or safety risk straight away", g:"documenting",
  h:"asking for advice or guidance", i:"delaying or waiting", j:"avoiding the issue or protecting yourself", k:"asking someone else to deal with it",
  l:"fixing the system or reflecting", m:"dealing with it publicly or in a group", n:"bending the rules or going along with it"};
const sigOf = q => crypto.createHash("sha1").update(q.o.map(o => o[0]).join("\u0001")).digest("hex").slice(0, 8);
let tagData = {tags: [], sig: []};
try { tagData = JSON.parse(read("tools/tags.json")); } catch (e) { errors.push("tools/tags.json is missing or unreadable"); }
if (tagData.tags.length !== Q.length) errors.push(`tools/tags.json has ${tagData.tags.length} entries for ${Q.length} questions`);
else Q.forEach((q, i) => {
  const t = tagData.tags[i];
  if (typeof t !== "string" || t.length !== q.o.length || [...t].some(c => !TAG_LABELS[c])) errors.push(`Q${i + 1}: bad option tags "${t}"`);
  else if (tagData.sig[i] !== sigOf(q)) errors.push(`Q${i + 1}: options changed since they were tagged; re-tag it in tools/tags.json (new signature ${sigOf(q)})`);
});
if (errors.length) { console.error(errors.join("\n")); process.exit(1); }

// Difficulty audit (warnings only): the answer shouldn’t be guessable from length or giveaway wording.
const GIVEAWAY = /\b(lie|lying|pretend|ignore|shout|tell (?:her|him|them) off|refuse to discuss|in front of (?:the )?(?:patient|patients|everyone)|threaten|humiliat|make fun|say nothing)\b/i;
const warnings = [];
Q.forEach((q, i) => {
  const len = j => q.o[j][0].length, keyed = q.t === "best3" ? q.k.split("").map(c => "ABCDEFGH".indexOf(c)) : [q.k[0], q.k[1]].map(c => "ABCDE".indexOf(c));
  const rest = q.o.map((_, j) => j).filter(j => !keyed.includes(j));
  const avg = a => a.reduce((s, j) => s + len(j), 0) / a.length;
  const ratio = avg(keyed) / avg(rest);
  if (ratio > 1.3) warnings.push(`Q${i + 1}: keyed options are ${Math.round((ratio - 1) * 100)}% longer than the rest`);
  q.o.forEach(([t], j) => { if (GIVEAWAY.test(t)) warnings.push(`Q${i + 1} option ${"ABCDEFGH"[j]}: giveaway wording “${t.match(GIVEAWAY)[0]}”`); });
});
if (warnings.length) console.warn(`${warnings.length} difficulty warning(s):\n  ` + warnings.join("\n  "));

// Questions as the site displays them (options shuffled, keys in displayed letters), for "Explain my mistake".
const bank = Q.map(q => ({t: q.t, s: q.s.replace(/<[^>]+>/g, ""), o: q.o.map(o => [o[0], o[1]]), k: q.k, tk: q.tk}));
fs.writeFileSync(path.join(root, "src/explain-bank.js"), "// Generated by tools/build.js from docs/questions.js. Do not edit.\nexport default " + JSON.stringify(bank) + ";\n");


// Generated tag data: docs/tags.js for the browser, src/study-data.js for the Worker (which validates what the browser sends).
fs.writeFileSync(path.join(root, "docs/tags.js"), "// Generated by tools/build.js from tools/tags.json. Do not edit.\n// OPT_TAGS[i] has one action-type code per displayed option of question i+1.\nconst TAG_LABELS = " + JSON.stringify(TAG_LABELS) + ";\nconst OPT_TAGS = " + JSON.stringify(tagData.tags) + ";\n");
// Playbook text for the AI (so it can say what to read) and the code that picks which sections to point at.
const gctx = {}; vm.runInNewContext(read("docs/guide.js") + ";this.GUIDE=GUIDE;this.PLAYBOOKS=PLAYBOOKS;", gctx);
const plain = h => h.replace(/<[^>]+>/g, " ").replace(/&[a-z]+;/g, " ").replace(/\s+/g, " ").trim();
const GENERAL = ["priorities", "ladder", "traits", "traps", "technique", "checklist"];
const SECTIONS = {};
gctx.GUIDE.filter(g => GENERAL.includes(g.id)).forEach(g => { SECTIONS[g.id] = {title: g.title, text: plain(g.html).slice(0, 1100)}; });
Object.keys(THEMES).forEach(t => { const p = gctx.PLAYBOOKS[t]; if (!p) errors.push("no playbook for theme " + t);
  else SECTIONS[t] = {title: THEMES[t] + " playbook", text: "Usually ranks high: " + p.high.join("; ") + ". Usually ranks low: " + p.low.join("; ") + ". Nuance: " + p.note}; });
// Which general guide section explains each kind of action (see TAG_LABELS)
const TAG_READ = {a: "ladder", b: "ladder", c: "ladder", d: "traits", e: "priorities", f: "priorities", g: "traits", h: "ladder", i: "priorities", j: "traps", k: "ladder", l: "traits", m: "traps", n: "traps"};
Object.values(TAG_READ).forEach(id => { if (!SECTIONS[id]) errors.push("guide section missing: " + id); });
if (errors.length) { console.error(errors.join("\n")); process.exit(1); }
fs.writeFileSync(path.join(root, "src/study-data.js"), "// Generated by tools/build.js. Do not edit.\nexport const THEMES = " + JSON.stringify(THEMES) + ";\nexport const DOMAINS = " + JSON.stringify(DOMAINS) + ";\nexport const TAGS = " + JSON.stringify(TAG_LABELS) + ";\nexport const QA = " + JSON.stringify(Q.map(q => q.a)) + ";\nexport const QG = " + JSON.stringify(Q.map(q => q.g).join("")) + ";\nexport const SECTIONS = " + JSON.stringify(SECTIONS) + ";\nexport const TAG_READ = " + JSON.stringify(TAG_READ) + ";\nexport const OPT_TAGS = " + JSON.stringify(tagData.tags) + ";\n");

const types = Q.map(q => q.t === "best3" ? "b" : "r").join("");
const worker = read("src/worker.js").replace(/\/\/ TYPES:start[\s\S]*?\/\/ TYPES:end/, `// TYPES:start\nconst QTYPES = "${types}";\n// TYPES:end`);
fs.writeFileSync(path.join(root, "src/worker.js"), worker);

const files = ["index.html", "styles.css", "design.css", "questions.js", "guide.js", "app.js", "design.js", "phrases.js", "standards.js", "explain.js", "exam.js", "exam.css", "tags.js", "studyplan.js", "manifest.webmanifest"];
const hash = crypto.createHash("sha256"); files.forEach(f => hash.update(read("docs/" + f)));
hash.update(read("docs/sw.js").replace(/const VERSION = "[^"]*";/, "")); // changes to the service worker itself also rotate the cache
const version = hash.digest("hex").slice(0, 10);
fs.writeFileSync(path.join(root, "docs/sw.js"), read("docs/sw.js").replace(/const VERSION = "[^"]*";/, `const VERSION = "${version}";`));

const count = k => Q.filter(q => q.t === k).length;
console.log(`OK: ${Q.length} questions (${count("rank")} rank, ${count("consider")} consider, ${count("best3")} best-three). SW version ${version}.`);
